          "$12$, $60$, so a $\\TwoT$ draw clears both for all but the "
          f"dodecahedron, whose draw needs $\\TwoI$ (${mean_phi:.1f}\\,\\Phi$ "
          "per shot on average). \\textit{Naimark register} counts qubits, "
