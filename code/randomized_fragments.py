# anyway: that is measured, not enforced.
QUOTED_IN_PROSE = {
    "octahedron": r"$\Id$, $\mathbf{F}$, $\mathbf{F}^\dagger$",
    "cube": r"$\Id$, $\mathbf{F}$, $\mathbf{Z}$, $\mathbf{F}^\dagger$",
}


def latex_word(seq):
    """Atlas gate sequence -> LaTeX math, in the thesis's notation: the
    symmetrized gates bold, as in Appendix A (main.py's tex_seq), and Φ
    plain ('X F†' -> '$\\mathbf{X} \\mathbf{F}^\\dagger$', '' -> '$\\Id$')."""
    if seq in ("", "I"):
        return r"$\Id$"
    seq = re.sub(r"[XZFHS]", lambda m: r"\mathbf{" + m.group(0) + "}", seq)
    return "$" + seq.replace("Φ", r"\Phi").replace("†", r"^\dagger") + "$"


def coin_column(solid):
    """Sorted coin words and their (max depth, max magic), or None if no coin."""
    if not is_decomposable(load_vertices(solid)):
        return None
    g = COVARIANCE[solid]
    reps = coset_representatives(load_vertices(solid), load_rotations(g),
                                 best_circuits(load_atlas(g)))
    reps = sorted(reps, key=lambda r: (r[0], r[1], len(r[2]), r[2]))
    words = ", ".join(latex_word(seq) for _, _, seq in reps)
    if solid in QUOTED_IN_PROSE:
        assert words == QUOTED_IN_PROSE[solid], \
            (f"{solid} coin drifted from the words the thesis prints: "
             f"{words} != {QUOTED_IN_PROSE[solid]} -- the table and the prose "
             f"must be corrected together, not just regenerated")
    return words, max(r[1] for r in reps), max(r[0] for r in reps)


GROUP_TEX = {"T": r"\Tgroup", "O": r"\Ogroup", "I": r"\Igroup",
             # Klein four-group dressed as V_4: bare V is the thesis's vertex
             # count, and both senses print in tab:implementation-ledger.
             "V": "V_4", "C_3": "C_3", "C_4": "C_4", "C_5": "C_5",
             "D_3": "D_3", "D_4": "D_4", "D_5": "D_5", "1": r"\{\Id\}"}
DRAW_TEX = {12: r"\TwoT", 24: r"\TwoO", 60: r"\TwoI"}


def bar_cell(names, order):
    """'$C_4, V_4$ (4)' -- the subgroups at a bar, with the bar's order."""
    return "$" + ", ".join(GROUP_TEX[n] for n in names) + f"$ ({order})"


def spec_sheet():
    """Every cell of the master ledger, per solid, from the check primitives.

    One source of truth: the geometry off the canonical vertices, the
    register off V, the coin off coset_representatives, the two bars off
    two_bars/twirl_bar, the costs off the atlas's min-magic synthesis.
    """
    out = {}
    for solid in SOLIDS:
        s = load_vertices(solid)
        V = len(s)
        qb = math.ceil(math.log2(V))              # Naimark register dim >= V
        row = {"V": V, "design": design_strength(s), "qubits": qb,
               "dim": 2 ** qb, "dead": 2 ** qb - V,
               "demand": DEMAND_DISPLAY[solid], "twirl_bar": twirl_bar(solid)[0]}
        # The design column goes straight into the ledger the thesis prints,
        # and design_strength's docstring claims it agrees with
        # povm_properties' (2, 3, 3, 5, 5), so the claim is asserted here and
        # not merely made. The two derivations share no mechanism -- exact
        # moments over a number field there against float moment averaging
        # here -- so this is an independent verifier and not a control;
        # EXPECTED_DESIGN is the ladder's single source.
        assert row["design"] == EXPECTED_DESIGN[solid], (solid, row["design"])
        if not is_decomposable(s):
            assert solid == "tetrahedron"
            out[solid] = {**row, "axes": None, "coin": None, "realize": None,
                          "binds": None, "draw": 12, "draw_cost": None}
            continue
        b = two_bars(solid)
        assert b["bar_twirl"] == row["twirl_bar"]  # R1 and R2 agree on the bar
        R = b["rotations"]
        circuits = best_circuits(load_atlas(b["group"]))
        reps = coset_representatives(s, R, circuits)
        # the cheapest draw clearing both bars (several may tie at the draw)
        bill = min((max(circuits[rot_key(R[i])][0] for i in S),
                    max(circuits[rot_key(R[i])][1] for i in S))
                   for S in b["draw_groups"])
        out[solid] = {**row, "axes": V // 2,
                      "coin": (len(reps), max(r[1] for r in reps),
                               max(r[0] for r in reps)),
                      "realize": bar_cell(b["min_realize"], b["bar_realize"]),
                      "binds": b["binds"], "draw": b["draw"],
                      "draw_cost": (bill[1], bill[0])}
    return out


