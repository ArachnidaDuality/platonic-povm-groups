    # Permutation and kappa recomputed from the same primitives
    # check_decker_outcome_order asserted with: the permutation reads the
    # rebuilt circuit against the atlas through Table D.3's reorientation,
    # kappa through no correction at all -- the circuit as published,
    # outcomes read against the atlas list index for index. The cell is
    # two-line notation keyed by register value: three solids' live
    # outcomes are non-contiguous and the atlas numbers vertices from 1,
    # so neither row of the map may be left an implicit range(). The
    # column prints even though each card carries its own
    # register-to-vertex key: reading a card's rectangle key means decoding
    # the register in base 2, while the column reads at sight. The % key
    # comment lines are the machine-readable twin --
    # _build_povm_cards.py's assertion 15 and _build_recipe_figure.py read
    # them, and the card build's parse asserts print and twin equal.
    rows, keys = [], []
    for solid in SOLIDS:
        d, live, W = decker_vertices(solid)
        n = load_vertices(solid)
        V = len(n)
        assert live == sorted(live) and len(live) == V, solid
        dead = sorted(set(range(len(W))) - set(live))
        assert all(np.linalg.norm(W[k]) < 1e-12 for k in dead), solid
        R = np.array(REORIENT[solid][1], dtype=float)
        perm = []
        for vx in d:
            dist = np.linalg.norm(n - R @ vx, axis=1)
            near = np.sort(dist)[:2]
            assert near[0] < 1e-9 and near[1] > 0.1, (solid, near)
            perm.append(int(np.argmin(dist)))
        assert sorted(perm) == list(range(V)), solid
        kappa = float(np.mean([n[k] @ d[k] for k in range(V)]))
        # relabelling without the gate leaves the overlap at tr(R)/3
        # exactly (D.2's angle law), and the tetrahedron's printed row
        # (relabelling trivial) prices exactly that gap. The caption says
        # nothing of it: that row is the one solid where the half-measure is
        # benign, and it hides the octahedron's -0.179 (a 31x premium, worse
        # than skipping both corrections).
        kappa_perm = float(np.mean([n[perm[i]] @ d[i] for i in range(V)]))
        assert abs(kappa_perm - np.trace(R) / 3) < 1e-12, solid
        if solid == "tetrahedron":
            assert perm == list(range(V)) and kappa == kappa_perm
        top = " ".join(str(j) for j in live)
        bot = " ".join(str(p + 1) for p in perm)
        keys.append(f"% key {solid}: {top} -> {bot}")
        pi_cell = ("$\\bigl(\\begin{smallmatrix} "
                   + " & ".join(str(j) for j in live) + " \\\\ "
                   + " & ".join(str(p + 1) for p in perm)
                   + " \\end{smallmatrix}\\bigr)$")
        if solid == "cube":
            assert abs(kappa + 1 / 3) < 1e-12, kappa
            kap_cell = "$-1/3$ exactly"
        else:
            kap_cell = f"${kappa:+.6f}$"
        rows.append(f"  {solid.capitalize()} & {pi_cell} & {kap_cell}"
                    f" & ${1 / kappa ** 2:.2f}$ \\\\")
